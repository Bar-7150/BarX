export function productById(id: string) {
  return products.find((p) => p.id === id);
}

export function productBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function projectBySlug(slug: string) {
  return projects.find((p) => p.slug === slug);
}

export function projectCost(project: Project) {
  return project.components.reduce((sum, line) => {
    const p = productById(line.productId);
    return sum + (p ? p.price * line.quantity : 0);
  }, 0);
}

export function projectsUsing(productId: string) {
  return projects.filter((p) => p.components.some((c) => c.productId === productId));
}

export function categoryProducts(slug: string) {
  if (slug === "microcontrollers") {
    return products.filter((p) => ["esp32", "arduino", "raspberry-pi"].includes(p.category));
  }
  return products.filter((p) => p.category === slug);
}

